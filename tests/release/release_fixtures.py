"""Isolated manifest fixtures; release tests never bump the checkout itself."""
import json
from pathlib import Path
import sys

SCRIPTS = Path(__file__).resolve().parents[2] / "scripts"
if str(SCRIPTS) not in sys.path:
    sys.path.insert(0, str(SCRIPTS))


def make_project(root: Path, version: str = "1.2.3") -> None:
    (root / "src-tauri").mkdir()
    package = {"name": "tauri-app", "version": version, "scripts": {"test": "vitest"}, "dependencies": {"example": "1.2.3"}}
    lock = {"name": "tauri-app", "version": version, "lockfileVersion": 3, "packages": {
        "": {"name": "tauri-app", "version": version, "dependencies": {"example": "1.2.3"}},
        "node_modules/example": {"version": "1.2.3", "integrity": "unchanged"},
    }}
    for name, value in [("package.json", package), ("package-lock.json", lock), ("src-tauri/tauri.conf.json", {"version": version, "identifier": "com.ykworx.transrator"})]:
        (root / name).write_text(json.dumps(value, indent=2) + "\n")
    (root / "src-tauri/Cargo.toml").write_text(
        f'[package]\nname = "tauri-app"\nversion = "{version}" # app\n\n[dependencies]\nexample = "1.2.3"\n')
    (root / "src-tauri/Cargo.lock").write_text(
        '# This file is automatically generated by Cargo.\nversion = 3\n\n'
        '[[package]]\nname = "example"\nversion = "1.2.3"\nsource = "registry+https://example.invalid"\nchecksum = "unchanged"\n\n'
        f'[[package]]\nname = "tauri-app"\nversion = "{version}" # app\ndependencies = ["example"]\n')
